export function adminText(value, lang) {
  if (lang !== "Cn" || typeof value !== "string") return value;

  const text = value.trim();
  if (!text) return value;
  if (ADMIN_ZH[text]) return ADMIN_ZH[text];
  if (STATUS_ZH[text]) return STATUS_ZH[text];

  const normalizedStatus = text.toLowerCase().replaceAll(" ", "_");
  if (STATUS_ZH[normalizedStatus]) return STATUS_ZH[normalizedStatus];

  let match = text.match(/^(\d+) active$/);
  if (match) return `${match[1]} 家启用`;
  match = text.match(/^(\d+) quotes?$/);
  if (match) return `${match[1]} 份报价`;
  match = text.match(/^(\d+) risks?$/);
  if (match) return `${match[1]} 项风险`;
  match = text.match(/^(\d+) item rows?$/);
  if (match) return `${match[1]} 项明细`;
  match = text.match(/^(\d+) uploaded$/);
  if (match) return `已上传 ${match[1]} 个文件`;
  match = text.match(/^(\d+) missing$/);
  if (match) return `缺少 ${match[1]} 项`;
  match = text.match(/^(\d+) submissions?$/);
  if (match) return `${match[1]} 次提交`;
  match = text.match(/^(\d+) projects?(?: \/ (\d+) awaiting review)?$/);
  if (match) return `${match[1]} 个项目${match[2] ? ` / ${match[2]} 个待审核` : ""}`;
  match = text.match(/^(\d+) customers \/ (\d+) intake records$/);
  if (match) return `${match[1]} 个客户 / ${match[2]} 条订单接入记录`;
  match = text.match(/^Rank #(\d+)$/);
  if (match) return `排名 #${match[1]}`;
  match = text.match(/^(\d+) days · score (.+)$/);
  if (match) return `${match[1]} 天 · 评分 ${match[2]}`;
  match = text.match(/^(\d+) days$/);
  if (match) return `${match[1]} 天`;
  match = text.match(/^(.+) approved as selected supplier\.$/);
  if (match) return `已批准 ${match[1]} 为中选供应商。`;
  if (/ sourcing package$/i.test(text)) return text.replace(/ sourcing package$/i, " 询价包");

  return value;
}

const LOCALIZED_PROPS = ["title", "description", "status", "stage", "label", "placeholder", "aria-label", "alt"];

function localizeNode(node, lang) {
  if (typeof node === "string") return adminText(node, lang);
  if (Array.isArray(node)) return node.map((child) => localizeNode(child, lang));
  if (!React.isValidElement(node)) return node;

  const nextProps = {};
  LOCALIZED_PROPS.forEach((propName) => {
    if (typeof node.props[propName] === "string") nextProps[propName] = adminText(node.props[propName], lang);
  });

  if (node.type === "option" && node.props.value == null && typeof node.props.children === "string") {
    nextProps.value = node.props.children;
  }

  if (node.props.children !== undefined) {
    nextProps.children = React.Children.map(node.props.children, (child) => localizeNode(child, lang));
  }
  if (node.props.actions !== undefined) nextProps.actions = localizeNode(node.props.actions, lang);

  return React.cloneElement(node, nextProps);
}

export function AdminLocalized({ lang, children }) {
  return localizeNode(children, lang);
}
